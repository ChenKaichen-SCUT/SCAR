"""Selected real-state probe, with evaluator-supplied pending-trial binding.

The pending library trial is inherited from h2, NOT generated by the new arm.
The legacy prefix exhausted all 12 proposal calls. This diagnostic supplies
two extra calls by setting the local counter to 10; this is an explicit budget
intervention, not a native full-game result. After these injections, use the
actual frozen agent/LLM for at most four actions.
This is not an independent game result or an automatic semantic parse claim.
"""
import contextlib,copy,hashlib,json,os
from pathlib import Path
from scar.environment import AGENT_ID,restore,snapshot,state_digest
from scar.io import atomic_json
from scar_public.experiments.continuation_branch import ReusingProvider
from scar_public.experiments.core_trial import build_system
from scar_public.hypothesis_repair import HypothesisRepairAgent
from scar_public.objective_repair import ObjectiveRepairAgent,TrialEvidence,requirement_catalog
from scar_public.continuation import task_key
from scar_public.provider import usage_summary

root=Path('/root/scar_objective_v3_20261018');out=root/'revision_probe';out.mkdir(exist_ok=True)
old=Path('/root/scar_hypothesis_v2_20261018/evaluation/mark_r1')
block=Path('/root/scar_core_valid_20261017/evaluation/mark_r1')
assert os.environ['PYTHONHASHSEED']==json.loads((block/'manifest.json').read_text())['hash_seed']
provider=ReusingProvider(out/'api','/root/scar_research_20261015/private/deepseek.key',historical=block/'api',
    additional_historical=[Path('/root/scar_hypothesis_20261018/evaluation/mark_r1/api'),old/'api'])
provider.cache_only=True;provider.arm='selected_revision_probe'
state=(block/'initial.pkl').read_bytes();system=build_system(restore(state),provider.model)
agent=HypothesisRepairAgent(provider,system)
with (out/'replay.log').open('w') as log,contextlib.redirect_stdout(log):
    for step in range(188):
        row=json.loads((old/'trace'/f'{step+1:04d}.json').read_text());provider.step=step
        env=restore(state,out/'private_replay')
        assert state_digest(env)==row['before_digest']
        action,*_=agent.act(dict(text=row['observation'],step=step))
        assert action==row['action'],step
        env=restore(state,out/'private_replay');obs,reward,done,_=env.step({AGENT_ID:action});env.update_scores(reward)
        assert state_digest(env)==row['after_digest'] and obs[AGENT_ID]['text']==row['next_observation']
        state=snapshot(env)
agent.__class__=ObjectiveRepairAgent
agent.trial_evidence=TrialEvidence();agent.revision_due=None
old_program=agent.hypothesis_pending['program']
candidate={k:old_program[k] for k in ('goal_quote','blocker','hypothesis','task_link','basis','steps','branches')}
goals=[candidate['goal_quote']];task=task_key(agent.notebook)
original={**row['response'],'action':row['response']['continuation']['original']}
needs=requirement_catalog(agent.notebook,original,goals,agent.continuation)
need=next(n for n in needs if n['target']=='copper_bar')
candidate.update(need_id=need['id'],verification=dict(mode='source',site='library'))
# The program already ran under h2; compile its verification without admitting
# it as a fresh new attempt, which would correctly trigger duplicate checks.
from scar_public.objective_repair import compile_verification
compiled,errors=compile_verification(candidate,needs);assert not errors
agent.hypothesis_pending['program']=dict(old_program,objective=compiled)
legacy_queries=len(agent.hypothesis_queries);assert legacy_queries==12
agent.hypothesis_queries=agent.hypothesis_queries[:10]
initial_queries=len(agent.hypothesis_queries)
provider.cache_only=False
rows=[]
with (out/'continuation.log').open('w') as log,contextlib.redirect_stdout(log):
    for step in range(188,192):
        provider.step=step;env=restore(state,out/'environment');text=env.obs[AGENT_ID]['text'];before=state_digest(env)
        action,inp,outp,response=agent.act(dict(text=text,step=step));parsed=json.loads(response)
        env=restore(state,out/'environment');obs,reward,done,_=env.step({AGENT_ID:action});env.update_scores(reward)
        following=obs[AGENT_ID]['text'];after=state_digest(env)
        replay=restore(state,out/'replay');ro,rr,rd,_=replay.step({AGENT_ID:action});replay.update_scores(rr)
        assert state_digest(replay)==after and ro[AGENT_ID]['text']==following
        rows.append(dict(step=step+1,observation=text,action=action,response=parsed,next_observation=following,
                         before_digest=before,after_digest=after,scores=env.scores[AGENT_ID]))
        state=snapshot(env)
        if done or not agent.hypothesis_pending:break
    agent.observe_terminal(dict(text=following,step=step+1))
result=dict(qualification=__doc__,prefix_replays=188,new_transition_replays=len(rows),
    evaluator_supplied_binding=candidate,legacy_proposal_calls=legacy_queries,
    budget_intervention='Two supplemental proposal calls for this selected diagnostic only',initial_proposal_calls=initial_queries,
    final_proposal_calls=len(agent.hypothesis_queries),rows=rows,outcomes=agent.obstacle_outcomes[-8:],
    trial_evidence=agent.trial_evidence.records,usage=usage_summary(out/'api'),
    evaluator_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
atomic_json(out/'result.json',result)
print(json.dumps(dict(prefix_replays=188,new_steps=len(rows),initial_calls=initial_queries,final_calls=len(agent.hypothesis_queries),
    actions=[r['action'] for r in rows],usage=result['usage'])))
