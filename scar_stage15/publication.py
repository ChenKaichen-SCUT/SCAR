"""Reconcile published numbers, frozen policies, raw requests and native replays."""
from collections import Counter
import datetime
import json
from pathlib import Path
import re
from scar.io import atomic_json
from scar_stage14.common import load,sha,records
ROOT=Path('results/stage15')


def main():
    frozen=load(ROOT/'freeze.json');prior=load(ROOT/'prior_manifest.json')
    for p,h in (prior|frozen['code_hashes']|frozen['data_hashes']).items():assert sha(p)==h,p
    verification=load(ROOT/'verification.json');local=load(ROOT/'local_verification.json')
    assert verification['passed'] and local['passed'] and verification['digest']==local['digest']
    assert verification['episodes']==local['episodes']==70 and verification['repeats']==2
    summary=load(ROOT/'aggregate_metrics.json');completion=load(ROOT/'completion.json');metric=load(ROOT/'episode_metrics.json')
    cases=load('results/stage11/cases.json');families={c['id'] for c in cases}
    total_actions=0;total_cost=0;total_requests=0;ids=set();earliest=float('inf');last=0;taskids=set()
    actual_requests={};models=Counter()
    for method in [f'P{i}' for i in range(7)]:
        eps=list(records(ROOT/f'trajectories_{method}.jsonl.gz'));rs=[r['request'] for r in records(ROOT/f'requests_{method}.jsonl.gz')]
        assert len(eps)==10 and {e['case_id'] for e in eps}==families
        steps=sum(len(e['rows']) for e in eps);successes=sum(any(r['diagnostic_goal_reached'] for r in e['rows']) for e in eps)
        assert steps==summary[method]['steps'] and successes==summary[method]['R40']
        cost=sum(r.get('cost_usd',0) for r in rs);assert abs(cost-summary[method]['cost_usd'])<1e-9
        assert summary[method]['api_calls']==len(rs)
        for ep in eps:
            assert ep['task_id'] not in taskids;taskids.add(ep['task_id'])
            assert len(ep['rows'])<=40 and ep['summary']['game']=='robot_kingdom'
            assert all(not r['extra_repair_call'] for r in ep['rows'])
            assert ep['summary']['algorithm']==method
        for request in rs:
            assert request['request_id'] not in ids;ids.add(request['request_id']);actual_requests[request['request_id']]=request
            assert request['model']=='deepseek-flash' and request['thinking']=='disabled'
            models[(request.get('raw_response') or {}).get('model','NO_RESPONSE')]+=1
            earliest=min(earliest,request['start']);last=max(last,request['end'])
        total_actions+=steps;total_cost+=cost;total_requests+=len(rs)
    assert earliest>datetime.datetime.fromisoformat(frozen['time_utc']).timestamp()
    ledger=load(ROOT/'budget_ledger.json');byledger={r['id']:r for r in ledger}
    assert ids<=set(byledger)
    for requestid,r in actual_requests.items():
        assert abs(byledger[requestid]['charged']-r['charged_or_reserved_usd'])<1e-9
    assert not any(r['charged'] is None for r in ledger)
    assert abs(total_cost-completion['cost_usd'])<1e-9
    assert total_actions==verification['actions']==local['actions']==completion['actions']
    assert total_requests==completion['api_calls']
    original=load(ROOT/'original_checkpoint_verification.json')
    assert original['passed'] and original['original_formal_checkpoint_hashes_matched']==total_actions
    assert completion['conservative_cost_usd']<=5
    required=['知识解析与数量执行.md','目标收尾与材料保护.md','探索额度有限续行.md','消融实验与逐例分析.md','实验总报告.md','复现指南.md','研究判断.md']
    assert all((Path('reports/stage15')/n).is_file() for n in required)
    files=[p for root in ['scar_stage15','results/stage15','reports/stage15'] for p in Path(root).rglob('*') if p.is_file() and '__pycache__' not in str(p) and p.suffix not in {'.pyc'}]
    files.append(Path('configs/protocol_stage15.json'))
    # Only scan newly authored text, never read credentials. Raw request logs are
    # generated by the existing sanitized provider and contain no HTTP headers.
    for p in files:
        if p.suffix in {'.json','.py','.md','.txt'}:
            text=p.read_text()
            assert not re.search(r'sk-[A-Za-z0-9_-]{24,}',text),f'possible secret in {p}'
    result={'passed':True,'historical_files_unchanged':len(prior),'frozen_code_and_data_unchanged':True,
        'all70accounted':True,'actions':total_actions,'api_calls':total_requests,'cost_usd':total_cost,
        'conservative_cost_usd':completion['conservative_cost_usd'],'served_models':dict(models),'raw_requests_ledger_reconciled':True,
        'first_request_utc':datetime.datetime.fromtimestamp(earliest,datetime.timezone.utc).isoformat(),
        'last_request_utc':datetime.datetime.fromtimestamp(last,datetime.timezone.utc).isoformat(),
        'elapsed_api_span_seconds':last-earliest,'original_saved_states_verified':True,'native_server_and_local_equal':True,'paid_reruns':0,
        'required_reports_present':True,'successes':{m:a['R40'] for m,a in summary.items()},
        'no_independent_generalization_claim':True}
    atomic_json(ROOT/'publication_checks.json',result)
    files.append(ROOT/'publication_checks.json')
    manifest={str(p):sha(p) for p in sorted(set(files)) if p.name!='publication_manifest.json'}
    atomic_json(ROOT/'publication_manifest.json',manifest)
    print(json.dumps(result))

if __name__=='__main__':main()
